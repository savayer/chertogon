let lang = 'ru';

export const getLang = () => lang;

export function setLang(next) {
  if (STRINGS[next]) lang = next;
}

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
